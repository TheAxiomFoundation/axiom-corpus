SELECTORS = {("vt", "statute"): "ul.statutes-detail"}


def version_for(st: str, document_class: str) -> str:
    return f"2026-11-24-ui-benefits-{document_class}-{st}"


def manifests() -> dict[tuple[str, str], dict]:
    grouped: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for st, document_class, tail, title, url, fmt, extra in DOCS:
        path = f"us-{st}/{document_class}/{tail}"
        if path in HELD:
            continue
        entry = {
            "source_id": path.replace("/", "-").replace(".", "-"),
            "jurisdiction": f"us-{st}",
            "document_class": document_class,
            "title": title,
            "source_url": url,
            "source_format": fmt,
            "source_as_of": AS_OF,
            "expression_date": extra.get("expression_date", AS_OF),
            "citation_path": path,
            "metadata": {
                "primary_source": True,
                "source_authority": AUTHORITY[st]
                if document_class == G
                else "official publisher of the code",
                "program": "Unemployment insurance",
                "discovered_via": "axiom-roadmap-dashboard UI scope audit (a9a977bc), not reviewed by a person",
                "run_note": RUN_NOTE,
            },
        }
        if (st, document_class) in SELECTORS:
            entry["extraction"] = {"html_content_selector": SELECTORS[(st, document_class)]}
        for key in ("download_url", "extraction", "request"):
            if key in extra:
                entry[key] = extra[key]
        grouped[(st, document_class)].append(entry)
    return {
        key: {"version": version_for(*key), "documents": documents}
        for key, documents in sorted(grouped.items())
    }


def main() -> None:
    for (st, document_class), manifest in manifests().items():
        path = REPO / "manifests" / f"us-{st}-ui-benefits-{document_class}.yaml"
        header = f"# Unemployment insurance benefits. Written by {Path(__file__).name}; run note {RUN_NOTE}.\n"
        path.write_text(
            header + yaml.safe_dump(manifest, sort_keys=False, width=110), encoding="utf-8"
        )
        print(path.relative_to(REPO), len(manifest["documents"]))


if __name__ == "__main__":
    main()
