def _nh_mam_leaves() -> list[dict[str, str]]:
    """Walk the NH Medical Assistance Manual RoboHelp TOC (whlstt*.htm, chrome120) to every section page."""
    base = "https://www.dhhs.nh.gov/mam_htm/whgdata/"

    def parse_lines(text: str) -> list[dict[str, Any]]:
        entries = []
        for m in re.finditer(r"((?:&nbsp;)*)<nobr>(.*?)</nobr>", text, re.S):
            level = (len(m.group(1)) // 6) // 3
            body = m.group(2)
            name_m = re.search(r'<a name="(\d+)"></a>', body)
            all_hrefs = re.findall(r'<a href="([^"]+)"[^>]*>(.*?)</a>', body)
            if not all_hrefs:
                continue
            href, title = all_hrefs[-1]
            entries.append({"level": level, "node_id": name_m.group(1) if name_m else None,
                            "href": href, "title": re.sub(r"<[^>]+>", "", title).strip()})
        return entries

    def prefix_level(text: str, node_id: str) -> int | None:
        m = re.search(r'((?:&nbsp;)*)<nobr><a name="' + re.escape(node_id) + r'">', text)
        return (len(m.group(1)) // 6) // 3 if m else None

    node_to_page = {"1": "whlstt1.htm"}
    children_of: dict[str, list[dict[str, Any]]] = {}
    to_visit, visited = ["1"], set()
    while to_visit:
        nid = to_visit.pop(0)
        if nid in visited:
            continue
        visited.add(nid)
        text = fetch_impersonated(base + node_to_page.get(nid, f"whlstt{nid}.htm"))
        entries = parse_lines(text)
        base_level = prefix_level(text, nid)
        if base_level is None:
            continue
        kids, found_self = [], False
        for e in entries:
            if not found_self:
                if e["node_id"] == nid:
                    found_self = True
                continue
            if e["level"] <= base_level:
                break
            if e["level"] == base_level + 1:
                kids.append(e)
        children_of[nid] = kids
        for c in kids:
            if c["node_id"]:
                page_m = re.match(r"(whlstt\d+\.htm)", c["href"])
                node_to_page[c["node_id"]] = page_m.group(1) if page_m else f"whlstt{c['node_id']}.htm"
                if c["node_id"] not in visited:
                    to_visit.append(c["node_id"])
    leaves, seen = [], set()
    for kids in children_of.values():
        for c in kids:
            if c["node_id"] or not c["href"].startswith("../html/"):
                continue
            fn = c["href"].split("/")[-1]
            if fn in seen:
                continue
            seen.add(fn)
            leaves.append({"file": fn, "title": c["title"], "url": "https://www.dhhs.nh.gov/mam_htm/html/" + fn})
    return leaves


