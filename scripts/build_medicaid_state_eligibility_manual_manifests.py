"""Build one official-document manifest per state for the state Medicaid eligibility
policy manuals (batch 1 of `manifests/medicaid-agent-queue.yaml`) and update the queue.

Every document is confirmed from the state Medicaid agency's own index page, fetched
live here so the manifest reflects what the publisher lists today. The lead-list
PolicyEngine citations in the queue are discovery only and are never used as sources.

Batch 1 = the two queued state rows (AR, VA) + the eight largest states by population
(CA, TX, FL, NY, PA, IL, OH, GA). Where a state's Medicaid eligibility chapters are
already in the corpus under a combined manual (FL, IL) the row is marked `done` with a
pointer and the next largest state is pulled (NC for IL; MI for FL, which is itself
already covered by the Bridges manual, so NJ is pulled). CA and OH block retrieval and
are recorded as `blocked_primary_source` with the exact failure.

    uv run python scripts/build_medicaid_state_eligibility_manual_manifests.py            # both batches
    uv run python scripts/build_medicaid_state_eligibility_manual_manifests.py --batch 2  # batch 2 only

Batch 2 = the next ten states by population (WA, AZ, TN, MA, IN, MD, MO, WI, CO, MN). None
was already covered by a combined manual in the corpus, so no replacement state was pulled.
AZ and TN block retrieval and are recorded as `blocked_primary_source` with the exact
failure; CA and OH were retried once each and their row notes record the outcome.

    uv run python scripts/build_medicaid_state_eligibility_manual_manifests.py --batch 3  # batch 3 only

Batch 3 = the next ten states by population (SC, AL, LA, KY, OR, OK, CT, UT, IA, NV) with MS, KS, NM,
NE, ID, WV as replacements, each publisher probed once. SC, AL, LA, KY, OR, UT, KS, NM and NE block
retrieval from this network and are recorded as `blocked_primary_source` with the exact failure; ID (IDAPA
16.03.01 and 16.03.05 already in the corpus as `us-id/regulation` at section granularity) and WV (Income
Maintenance Manual scope) are already covered (`done`, pointers); OK, CT, IA, NV and MS are built here.

    uv run python scripts/build_medicaid_state_eligibility_manual_manifests.py --batch 4  # batch 4 only

Batch 4 = the retry of every blocked_primary_source row from a US network (CA, OH, AZ, TN, SC, AL, LA, KY, OR, UT, KS,
NM, NE). OH, AZ, TN, SC, LA, KY, UT, KS and NM answer and are built here (set REQUESTS_CA_BUNDLE to
data/certs/medicaid-manuals-ca-bundle.pem for SC); CA and AL still block; OR and NE answer but are recorded
needs_review with the reason. Earlier batches are never regenerated by this batch (`--batch 4`).

    uv run python scripts/build_medicaid_state_eligibility_manual_manifests.py --batch 5  # batch 5 only

Batch 5 = the last jurisdictions on the map (AK, DC, DE, ND, RI, SD, VT, WY) plus the five needs_review rows (HI, ME,
NE, NH, OR), and the queue repair: any jurisdiction whose manifest exists on disk keeps its queue row whatever
`--batch N --only X` combination runs (`restore_missing_rows`; the us-ma and us-in rows lost in the batch-2 session are
rebuilt from their committed manifests and MANIFEST_ROW_FACTS). Earlier batches are never regenerated by this batch.
"""
