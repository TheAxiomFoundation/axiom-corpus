            body = fetch(f"{chapter_url}?page={n}")
            m = re.search(r"Page\s+(\d+)\s+of\s+(\d+)", body)
            for href, title_attr, number, intro in item_re.findall(body):
                href = html.unescape(href)
                clean = href.split("?", 1)[0]
