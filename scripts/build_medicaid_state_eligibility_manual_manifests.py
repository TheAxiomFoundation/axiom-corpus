def fetch_impersonated(url: str) -> str:
    """GET through curl-cffi chrome120 impersonation (TLS verification on) for publishers that answer HTTP 403
    to every plain client; used only where the plain request was tried first and failed. Transient connection
    errors (a dropped connection during a long TOC walk) are retried."""
    from curl_cffi import requests as curl_requests
    from curl_cffi.requests.exceptions import ConnectionError as CurlConnectionError

    for attempt in range(4):
        try:
            resp = curl_requests.get(url, impersonate="chrome120", timeout=90)
            resp.raise_for_status()
            return resp.text
        except CurlConnectionError:
            if attempt == 3:
                raise
            time.sleep(3 * (attempt + 1))
    raise AssertionError("unreachable")


def _robohelp_topics(base: str) -> list[tuple[str, str]]:
    """Walk an Adobe RoboHelp 2019+/2022 responsive output's whxdata/toc.new.js tree (the MN/PA pattern)."""

    def toc(key: str) -> list[dict[str, Any]]:
        text = fetch(f"{base}whxdata/{key}.new.js")
        m = re.search(r"var toc =\s*(\[.*?\]);\s*window", text, re.S)
        return json.loads(m.group(1)) if m else []

    entries: list[tuple[str, str]] = []

    def walk(key: str) -> None:
        for item in toc(key):
            if item.get("url"):
                entries.append((item.get("name", ""), item["url"].split("#", 1)[0]))
            if item.get("type") == "book" and item.get("key"):
                walk(item["key"])

    walk("toc")
    return entries


